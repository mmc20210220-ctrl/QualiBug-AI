    def _render_case(self, case: Dict[str, Any]) -> str:
        func_name = f"test_{case['case_id'].lower()}"
        lines = [
            f"def {func_name}():",
            f"    \"\"\"{case['title']}\"\"\"",
            "    service = AuthService()",
            "    ctx = {}",
        ]

        for action in case.get("actions", []):
            lines.extend(self._render_action(action))

        for assertion in case.get("assertions", []):
            lines.extend(self._render_assertion(assertion))

        return "\n".join(lines)

    def _render_action(self, action: Dict[str, Any]) -> List[str]:
        action_type = action["action"]
        alias = action.get("as")

        if action_type == "create_user":
            return [
                f"    ctx[{alias!r}] = service.create_user(role={action.get('role', 'user')!r}, status={action.get('status', 'active')!r})"
            ]

        if action_type == "login":
            username_expr = self._template_to_python(action["username"])
            password_expr = self._template_to_python(action["password"])
            return [
                f"    ctx[{alias!r}] = service.login({username_expr}, {password_expr})"
            ]

        if action_type == "login_wrong_password":
            times = int(action.get("times", 1))
            user_alias = action.get("user_alias", "user")
            lines = [f"    ctx[{alias!r}] = None"]
            lines.append(f"    for _ in range({times}):")
            lines.append(f"        ctx[{alias!r}] = service.login(ctx[{user_alias!r}]['username'], 'wrong-password')")
            lines.append(f"    # Execution State Guard: sync snapshot profile when the system returns ACCOUNT_LOCKED")
            lines.append(f"    if isinstance(ctx[{alias!r}], dict) and ctx[{alias!r}].get('error_code') == 'ACCOUNT_LOCKED':")
            lines.append(f"        ctx[{user_alias!r}]['status'] = 'locked'")
            return lines

        if action_type == "check_access":
            username_expr = self._template_to_python(action["username"])
            resource = action["resource"]
            return [
                f"    ctx[{alias!r}] = service.can_access({username_expr}, {resource!r})"
            ]

        raise ValueError(f"Unsupported DSL action: {action_type}")

    def _render_assertion(self, assertion: Dict[str, Any]) -> List[str]:
        target = assertion["target"]
        operator = assertion["operator"]
        expected = assertion["value"]
        actual_expr = self._target_to_python(target)

        if operator == "equals":
            return [f"    assert {actual_expr} == {expected!r}"]

        raise ValueError(f"Unsupported assertion operator: {operator}")

    def _template_to_python(self, value: str) -> str:
        if value.startswith("{{") and value.endswith("}}"):
            path = value[2:-2].strip()
            return self._target_to_python(path)
        return repr(value)

    def _target_to_python(self, dotted_path: str) -> str:
        parts = dotted_path.split(".")
        if parts[0] in {"user", "login_result", "last_wrong_result", "login_after_locked", "access_result"}:
            if len(parts) == 1:
                return f"ctx[{parts[0]!r}]"
            return f"read_path(ctx[{parts[0]!r}], {'.'.join(parts[1:])!r})"
        return f"read_path(ctx, {dotted_path!r})"
