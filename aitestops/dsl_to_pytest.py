def read_path(data, dotted_path):
    """Read dotted paths from generated test context.

    The function is intentionally tolerant because LLMs may describe a boolean
    result as access_result.allowed or account lock as locked=true. Semantic
    guard normalizes most cases before generation; this runtime reader is a
    second safety net for enterprise demos.
    """
    value = data
    for part in dotted_path.split("."):
        if isinstance(value, dict):
            if part in value:
                value = value[part]
                continue
            if part in {"locked", "is_locked", "account_locked"}:
                if "status" in value:
                    value = value.get("status") == "locked"
                    continue
                if "error_code" in value:
                    value = value.get("error_code") == "ACCOUNT_LOCKED"
                    continue
            if part in {"allowed", "is_allowed", "success", "result", "value"}:
                if "success" in value:
                    value = value.get("success")
                    continue
            if part in {"locked", "locked_user", "locked_normal_user"} and "login_after_locked" in value:
                value = value["login_after_locked"].get("error_code") == "ACCOUNT_LOCKED"
                continue
            return None
        if isinstance(value, bool):
            if part in {"allowed", "is_allowed", "success", "result", "value"}:
                return value
            return value
        value = getattr(value, part)
    return value
