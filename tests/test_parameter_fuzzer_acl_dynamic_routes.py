# ────────────────────────────────────────────────────────────────
# Test 6: Status code classification for all common HTTP codes
# ────────────────────────────────────────────────────────────────

@pytest.mark.parametrize("status,expected", [
    (200, True),    # 2xx success = could be bypass if wrong actor
    (201, True),
    (204, True),
    (301, False),   # 3xx redirect = not conclusive
    (302, False),
    (307, False),
    (401, False),   # 4xx auth = NOT bypass
    (403, False),   # 4xx auth = NOT bypass
    (404, False),   # 4xx route = environment issue, NOT bug
    (405, False),   # 4xx method = environment issue, NOT bug
    (422, False),   # 4xx validation = not ACL
    (500, False),   # 5xx = server error, not confirmed ACL
    (502, False),
    (503, False),
])
def test_status_code_classification(status, expected):
    """Systematic classification of HTTP status codes for ACL bypass detection."""
    is_bypass = (200 <= status < 300)
    assert is_bypass == expected, (
        f"HTTP {status}: expected is_bypass={expected}, got {is_bypass}"
    )
